void HD44780::reset() {
    m_ddram.fill(0x20);    // Space — clears the visible glyph grid
    m_cgram.fill(0);
    m_ac = 0;
    m_acIsCgram = false;
    m_displayOn = false;
    m_cursorOn  = false;
    m_blinkOn   = false;
    m_increment = true;
    m_busy = 0;
}

void HD44780::writeCommand(uint8_t cmd) {
    // MAME's hd44780_device::control_write decodes by leading bit; we
    // model only the operations the Organiser II ROM uses on the
    // happy path. A full port covers display-shift, cursor home,
    // function-set 4-bit-interface mode etc.
    if (cmd & 0x80) {
        // Set DDRAM address
        m_ac = cmd & 0x7F;
        m_acIsCgram = false;
    } else if (cmd & 0x40) {
        // Set CGRAM address
        m_ac = cmd & 0x3F;
        m_acIsCgram = true;
    } else if (cmd & 0x20) {
        // Function set — ignore details for now (4-bit/8-bit, lines).
    } else if (cmd & 0x10) {
        // Cursor / display shift — ignored in scaffold.
    } else if (cmd & 0x08) {
        // Display ON/OFF / cursor / blink
        m_displayOn = (cmd & 0x04) != 0;
        m_cursorOn  = (cmd & 0x02) != 0;
        m_blinkOn   = (cmd & 0x01) != 0;
    } else if (cmd & 0x04) {
        // Entry-mode set
        m_increment = (cmd & 0x02) != 0;
    } else if (cmd & 0x02) {
        // Return home
        m_ac = 0;
        m_acIsCgram = false;
    } else if (cmd & 0x01) {
        // Clear display
        m_ddram.fill(0x20);
        m_ac = 0;
        m_acIsCgram = false;
    }
}

void HD44780::writeData(uint8_t data) {
    if (m_acIsCgram) {
        if (m_ac < m_cgram.size()) m_cgram[m_ac] = data;
    } else {
        if (m_ac < m_ddram.size()) m_ddram[m_ac] = data;
    }
    if (m_increment) {
        m_ac = (m_ac + 1) & 0x7F;
    } else {
        m_ac = (m_ac - 1) & 0x7F;
    }
}

uint8_t HD44780::readStatus() const {
    // Bit 7 = busy flag (always 0 on this stub — a real port would
    // model the controller's tBUSY interval). Lower 7 bits = AC.
    return uint8_t((m_busy ? 0x80 : 0x00) | (m_ac & 0x7F));
}

uint8_t HD44780::readData() {
    uint8_t v = 0;
    if (m_acIsCgram) {
        if (m_ac < m_cgram.size()) v = m_cgram[m_ac];
    } else {
        if (m_ac < m_ddram.size()) v = m_ddram[m_ac];
    }
    if (m_increment) m_ac = (m_ac + 1) & 0x7F;
    else             m_ac = (m_ac - 1) & 0x7F;
    return v;
}

