// Psion LZ display layout — mapping from HD44780 cell index (DDRAM
// address relative to line base) to on-screen position (row*20+col,
// 0..79). Lifted verbatim from MAME's src/mame/psion/psion.cpp
// psion_display_layout[]. The LZ uses a custom HD66780 LCD controller
// (HD44780-compatible command set) wired in 2-line × 40-char mode but
// physically arranged as 4 rows × 20 cols. The layout array remaps the
// HD44780 cell index to the actual screen position so the OS can write
// linearly to DDRAM and have text appear correctly arranged.
//
// The array is indexed as `line*40 + pos`:
//   line 0 (entries 0-39):  DDRAM addresses $00-$27 (2 logical lines)
//   line 1 (entries 40-79): DDRAM addresses $40-$67
// Each entry's value is the screen position (0-79); divide by 20 for
// row, mod 20 for col.
static const uint8_t kPsionLayout[80] = {
    // line 0, pos 0-39 → DDRAM $00-$27:
    0x00, 0x01, 0x02, 0x03, 0x28, 0x29, 0x2A, 0x2B, 0x04, 0x05,
    0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x2C, 0x2D, 0x2E, 0x2F,
    0x30, 0x31, 0x32, 0x33, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11,
    0x12, 0x13, 0x34, 0x35, 0x36, 0x37, 0x38, 0x39, 0x3A, 0x3B,
    // line 1, pos 0-39 → DDRAM $40-$67:
    0x14, 0x15, 0x16, 0x17, 0x3C, 0x3D, 0x3E, 0x3F, 0x18, 0x19,
    0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F, 0x40, 0x41, 0x42, 0x43,
    0x44, 0x45, 0x46, 0x47, 0x20, 0x21, 0x22, 0x23, 0x24, 0x25,
    0x26, 0x27, 0x48, 0x49, 0x4A, 0x4B, 0x4C, 0x4D, 0x4E, 0x4F,
};

void HD44780::renderFramebuffer(uint8_t *out, int outW, int outH) const {
    if (!out || outW <= 0 || outH <= 0) return;
    std::memset(out, 0, size_t(outW) * size_t(outH));
    if (!m_displayOn) return;

    // Walk the HD44780 cell-index space (line 0/1, pos 0-39) and look up
    // each cell's screen position via the layout. Read the DDRAM byte
    // for that cell, render the glyph at the screen position.
    for (int idx = 0; idx < 80; idx++) {
        // Translate cell index to DDRAM address. line 0 base = $00,
        // line 1 base = $40.
        int line = idx / 40;
        int pos  = idx % 40;
        uint8_t ddramAddr = uint8_t(line * 0x40 + pos);
        uint8_t code = m_ddram[ddramAddr & 0x7F];
        // Layout maps cell index to screen position.
        uint8_t screenPos = kPsionLayout[idx];
        int row = screenPos / 20;
        int col = screenPos % 20;
        const uint8_t *glyph = nullptr;
        uint8_t cgram_glyph[8] = {};
        if (code < 16) {
            // CGRAM glyph 0-7. The HD44780 maps codes 0-7 to CGRAM
            // and codes 8-15 to a MIRROR of 0-7 (the high bit of the
            // 4-bit index is ignored when accessing CGRAM).
            for (int i = 0; i < 8; i++) {
                cgram_glyph[i] = m_cgram[(code & 0x07) * 8 + i] & 0x1F;
            }
            glyph = cgram_glyph;
        } else if (code >= 0x20 && code < 0x80) {
            glyph = CGROM_A00[code - 0x20];
        }
        if (!glyph) continue;
        // Paint at the cell's pixel position.
        for (int gy = 0; gy < 8; gy++) {
            int py = row * CELL_H + gy;
            if (py >= outH) break;
            uint8_t row_bits = glyph[gy];
            for (int gx = 0; gx < 5; gx++) {
                int px = col * CELL_W + gx;
                if (px >= outW) break;
                if (row_bits & (1 << (4 - gx))) {
                    out[py * outW + px] = 1;
                }
            }
        }
    }
}
