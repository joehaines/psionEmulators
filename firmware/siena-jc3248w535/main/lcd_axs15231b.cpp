void Lcd::command(uint8_t cmd, const uint8_t *data, size_t len) {
    ESP_ERROR_CHECK(esp_lcd_panel_io_tx_param(
        m_io, int((kOpWriteCmd << 24) | (uint32_t(cmd) << 8)), data, len));
}

bool Lcd::onTransferDone(esp_lcd_panel_io_handle_t, esp_lcd_panel_io_event_data_t *,
                         void *ctx) {
    BaseType_t woken = pdFALSE;
    xSemaphoreGiveFromISR(static_cast<Lcd *>(ctx)->m_free, &woken);
    return woken == pdTRUE;
}

esp_err_t Lcd::init() {
    // Backlight off until the first frame is up, so power-on garbage in
    // the panel's frame memory never shows.
    ledc_timer_config_t timer = {};
    timer.speed_mode = LEDC_LOW_SPEED_MODE;
    timer.duty_resolution = LEDC_TIMER_10_BIT;
    timer.timer_num = LEDC_TIMER_1;
    timer.freq_hz = 5000;
    timer.clk_cfg = LEDC_AUTO_CLK;
    ESP_ERROR_CHECK(ledc_timer_config(&timer));
    ledc_channel_config_t channel = {};
    channel.gpio_num = board::kLcdBacklight;
    channel.speed_mode = LEDC_LOW_SPEED_MODE;
    channel.channel = kBacklightChannel;
    channel.timer_sel = LEDC_TIMER_1;
    channel.duty = 0;
    ESP_ERROR_CHECK(ledc_channel_config(&channel));

    spi_bus_config_t bus = {};
    bus.sclk_io_num = board::kLcdClk;
    bus.data0_io_num = board::kLcdD0;
    bus.data1_io_num = board::kLcdD1;
    bus.data2_io_num = board::kLcdD2;
    bus.data3_io_num = board::kLcdD3;
    bus.data4_io_num = bus.data5_io_num = bus.data6_io_num = bus.data7_io_num = -1;
    bus.max_transfer_sz = kWidth * kStripRows * 2;
    ESP_ERROR_CHECK(spi_bus_initialize(kHost, &bus, SPI_DMA_CH_AUTO));

    m_free = xSemaphoreCreateCounting(2, 2);
    esp_lcd_panel_io_spi_config_t io = {};
    io.cs_gpio_num = board::kLcdCs;
    io.dc_gpio_num = GPIO_NUM_NC;
    io.spi_mode = 3;
    io.pclk_hz = kPixelClockHz;
    io.trans_queue_depth = 4;
    io.on_color_trans_done = &Lcd::onTransferDone;
    io.user_ctx = this;
    io.lcd_cmd_bits = 32;
    io.lcd_param_bits = 8;
    io.flags.quad_mode = 1;
    ESP_ERROR_CHECK(esp_lcd_new_panel_io_spi(esp_lcd_spi_bus_handle_t(kHost), &io, &m_io));

    for (auto &strip : m_strip) {
        strip = static_cast<uint16_t *>(heap_caps_malloc(
            kWidth * kStripRows * 2, MALLOC_CAP_DMA | MALLOC_CAP_INTERNAL));
        if (!strip) return ESP_ERR_NO_MEM;
    }

    // No reset line on this board: software reset, then the vendor set-up.
    command(kCmdSwReset);
    vTaskDelay(pdMS_TO_TICKS(120));
    command(kCmdSleepOut);
    vTaskDelay(pdMS_TO_TICKS(100));
    const uint8_t madctl = 0x00, colmod = 0x55;    // RGB order, 16 bpp
    command(kCmdMadctl, &madctl, 1);
    command(kCmdColmod, &colmod, 1);
    for (const InitCmd &c : kInitCmds) {
        command(c.cmd, c.len ? c.data : nullptr, c.len);
        if (c.delayMs) vTaskDelay(pdMS_TO_TICKS(c.delayMs));
    }
    command(kCmdDisplayOn);
    ESP_LOGI(TAG, "AXS15231B up, %dx%d", kWidth, kHeight);
    return ESP_OK;
}

void Lcd::setBacklight(int percent) {
    percent = percent < 0 ? 0 : (percent > 100 ? 100 : percent);
    ledc_set_duty(LEDC_LOW_SPEED_MODE, kBacklightChannel, uint32_t(1023 * percent / 100));
    ledc_update_duty(LEDC_LOW_SPEED_MODE, kBacklightChannel);
}

void Lcd::drawFrame(const std::function<void(int, int, uint16_t *)> &fill) {
    // tx_param waits for queued pixel transfers, so the column window is
    // set only after the previous frame has fully gone out.
    const uint8_t caset[4] = { 0, 0, uint8_t((kWidth - 1) >> 8), uint8_t((kWidth - 1) & 0xFF) };
    command(kCmdCaset, caset, sizeof caset);
    for (int row = 0, n = 0; row < kHeight; row += kStripRows, ++n) {
        xSemaphoreTake(m_free, portMAX_DELAY);
        uint16_t *buf = m_strip[n & 1];
        fill(row, kStripRows, buf);
        const uint8_t cmd = row == 0 ? kCmdRamwr : kCmdRamwrc;
        ESP_ERROR_CHECK(esp_lcd_panel_io_tx_color(
            m_io, int((kOpWriteColor << 24) | (uint32_t(cmd) << 8)), buf,
            size_t(kWidth) * kStripRows * 2));
    }
}
